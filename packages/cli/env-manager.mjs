import {
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
  existsSync,
} from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import {
  cosHeadObject,
  cosGetJson,
  cosListKeys,
  assertCloudEndpointsConfigured,
  MYSHIP_CONFIG_PATH,
} from './cos-client.mjs';
import {
  DEFAULT_STORAGE_DIR,
  ensureStorageDirs,
  normalizeDomainToken,
} from './project-context.mjs';

export const MYSHIP_ENVS_POOL_PATH = resolve(
  dirname(MYSHIP_CONFIG_PATH),
  'envs-pool.json'
);

export function loadLocalEnvsPool() {
  try {
    if (existsSync(MYSHIP_ENVS_POOL_PATH)) {
      return JSON.parse(readFileSync(MYSHIP_ENVS_POOL_PATH, 'utf8')) || {};
    }
  } catch {
    // ignore
  }
  return {};
}

export function saveLocalEnvsPool(pool) {
  mkdirSync(dirname(MYSHIP_ENVS_POOL_PATH), { recursive: true });
  writeFileSync(MYSHIP_ENVS_POOL_PATH, JSON.stringify(pool, null, 2), {
    encoding: 'utf8',
    mode: 0o600,
  });
}

export function assertValidEnvKey(key) {
  const k = String(key || '').trim();
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) {
    throw new Error(
      `环境变量名格式无效 (${key}): 仅支持字母、数字与下划线，且不能以数字开头。`
    );
  }
  return k;
}

export function maskEnvValue(val) {
  const s = String(val ?? '');
  if (s.length <= 4) return '****';
  if (s.length <= 8) return `${s.slice(0, 2)}****`;
  return `${s.slice(0, 3)}****${s.slice(-2)}`;
}

export function parseDotEnv(content) {
  const result = {};
  const lines = String(content || '').split(/\r?\n/);
  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const withoutExport = trimmed.startsWith('export ')
      ? trimmed.slice('export '.length).trim()
      : trimmed;
    const eqIdx = withoutExport.indexOf('=');
    if (eqIdx <= 0) continue;
    const key = assertValidEnvKey(withoutExport.slice(0, eqIdx).trim());
    let val = withoutExport.slice(eqIdx + 1).trim();
    if (val.startsWith('"')) {
      let endIdx = -1;
      for (let i = 1; i < val.length; i++) {
        if (val[i] === '\\') {
          i++;
          continue;
        }
        if (val[i] === '"') {
          endIdx = i;
          break;
        }
      }
      if (endIdx !== -1) {
        val = val
          .slice(1, endIdx)
          .replace(/\\([nr"\\])/g, (_, ch) => (ch === 'n' ? '\n' : ch === 'r' ? '\r' : ch));
      }
    } else if (val.startsWith("'")) {
      const endIdx = val.indexOf("'", 1);
      if (endIdx !== -1) {
        val = val.slice(1, endIdx);
      }
    } else {
      const commentIdx = val.indexOf(' #');
      if (commentIdx !== -1) {
        val = val.slice(0, commentIdx).trim();
      }
    }
    result[key] = val;
  }
  return result;
}

export function formatDotEnv(vars = {}) {
  const lines = ['# Generated by `myship env pull`'];
  for (const key of Object.keys(vars).sort()) {
    const val = String(vars[key] ?? '');
    const needsQuotes = /[\s#"'\r\n\\]/.test(val);
    const escaped = needsQuotes
      ? `"${val
          .replace(/\\/g, '\\\\')
          .replace(/"/g, '\\"')
          .replace(/\r/g, '\\r')
          .replace(/\n/g, '\\n')}"`
      : val;
    lines.push(`${key}=${escaped}`);
  }
  return lines.join('\n') + '\n';
}

export function getLocalProjectEnv(project = 'default', storageDir = DEFAULT_STORAGE_DIR) {
  ensureStorageDirs(storageDir);
  const cleanProj = normalizeDomainToken(project) || 'default';
  const envPath = resolve(storageDir, 'envs', `${cleanProj}.json`);
  if (!existsSync(envPath)) return {};
  const doc = JSON.parse(readFileSync(envPath, 'utf8'));
  if (!doc || typeof doc.vars !== 'object') {
    throw new Error(`本地环境变量文件格式损坏: ${envPath}`);
  }
  return { ...doc.vars };
}

export function saveLocalProjectEnv(
  project = 'default',
  vars = {},
  storageDir = DEFAULT_STORAGE_DIR
) {
  ensureStorageDirs(storageDir);
  const cleanProj = normalizeDomainToken(project) || 'default';
  const envPath = resolve(storageDir, 'envs', `${cleanProj}.json`);
  const payload = {
    project: cleanProj,
    updatedAt: new Date().toISOString(),
    vars,
  };
  writeFileSync(envPath, JSON.stringify(payload, null, 2), 'utf8');
  return payload;
}

export function loadDevProjectEnv(
  project = 'default',
  cwd = process.cwd(),
  storageDir = DEFAULT_STORAGE_DIR
) {
  const cleanProj = normalizeDomainToken(project) || 'default';
  let sandboxVars = {};
  try {
    sandboxVars = getLocalProjectEnv(cleanProj, storageDir);
  } catch {
    sandboxVars = {};
  }

  let dotEnvVars = {};
  const dotEnvPath = resolve(cwd, '.env');
  if (existsSync(dotEnvPath) && statSync(dotEnvPath).isFile()) {
    try {
      dotEnvVars = parseDotEnv(readFileSync(dotEnvPath, 'utf8'));
    } catch {
      dotEnvVars = {};
    }
  }

  let dotEnvLocalVars = {};
  const dotEnvLocalPath = resolve(cwd, '.env.local');
  if (existsSync(dotEnvLocalPath) && statSync(dotEnvLocalPath).isFile()) {
    try {
      dotEnvLocalVars = parseDotEnv(readFileSync(dotEnvLocalPath, 'utf8'));
    } catch {
      dotEnvLocalVars = {};
    }
  }

  return {
    ...dotEnvVars,
    ...dotEnvLocalVars,
    ...sandboxVars,
  };
}

export function buildProjectEnvsBlock(envsPool = {}) {
  const entries = [];
  const sortedProjects = Object.keys(envsPool).sort();
  for (const proj of sortedProjects) {
    const vars = envsPool[proj];
    if (!vars || typeof vars !== 'object') continue;
    entries.push(`  ${JSON.stringify(proj)}: ${JSON.stringify(vars)},`);
  }
  return entries.join('\n');
}

export async function syncCloudEnvsPool() {
  const envKeys = await cosListKeys('envs/');
  const pool = {};
  for (const key of envKeys) {
    if (!key.endsWith('.json')) continue;
    const proj = basename(key, '.json');
    const remoteDoc = await cosGetJson(key);
    if (
      !remoteDoc ||
      typeof remoteDoc !== 'object' ||
      !remoteDoc.vars ||
      typeof remoteDoc.vars !== 'object'
    ) {
      throw new Error(
        `同步云端项目环境变量失败 (${key}): 无法读取或格式异常，已安全中止操作以防覆盖丢失线上环境变量配置。`
      );
    }
    pool[proj] = remoteDoc.vars;
  }
  saveLocalEnvsPool(pool);
  return pool;
}

export async function getRemoteProjectEnv(project = 'default') {
  assertCloudEndpointsConfigured();
  const cleanProj = normalizeDomainToken(project) || 'default';
  const envKey = `envs/${cleanProj}.json`;
  const exists = await cosHeadObject(envKey);
  if (!exists) return {};
  const remoteDoc = await cosGetJson(envKey);
  if (!remoteDoc || typeof remoteDoc.vars !== 'object') {
    throw new Error(`读取云端项目环境变量失败 (${envKey}): 响应为空或格式损坏，已安全中止。`);
  }
  return { ...remoteDoc.vars };
}
